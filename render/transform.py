"""Render the translation JSON files in translations/ as Markdown files in md_files/.

Usage: python render/transform.py

- Needs only the Python standard library.
- Exits with status 1 if any translation cannot be rendered (the other files are
  still rendered, and the problems are listed at the end).
- A page keeps its previous "date:" unless its content changed, so re-running the
  script does not touch unchanged files.
- Markdown files that no longer have a matching JSON file are deleted.
"""
import json
import os
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TRANSLATIONS_DIR = ROOT / "translations"
MD_DIR = ROOT / "md_files"

# The English source text every translation is shown next to.
SOURCE_FILE = "en_Latn.json"
# Front matter line that marks a Markdown file as generated by this script.
GENERATED_MARKER = 'layout: "translation/single"'
JSON_URL = "https://github.com/contributorshipcollaboration/credit-translation/blob/main/translations"
DATE_RE = re.compile(r"^date: (\d{4}-\d{2}-\d{2})$", re.MULTILINE)
ON_GITHUB = os.environ.get("GITHUB_ACTIONS") == "true"


def today():
    return date.today().isoformat()


def load_json(path):
    # utf-8-sig tolerates a byte-order mark; scripts/validate.py reports it as an error
    return json.loads(path.read_text(encoding="utf-8-sig"))


def full_name(translator):
    """First, middle and last name, skipping a missing or empty middle name."""
    parts = (translator.get("firstName"), translator.get("middleName"), translator.get("lastName"))
    return " ".join(part for part in parts if part)


def json_to_md(json_data, en_data, filename, page_date):
    """Convert one translation to Markdown text."""
    language_name = json_data["metadata"]["languageName"]

    md_content = f"""---
title: "{language_name} translation of CRediT"
date: {page_date}
language: "{language_name}"
{GENERATED_MARKER}
githublink: "{JSON_URL}/{filename}"
---

"""

    # Translations section as a table
    md_content += f"| {language_name} | English |\n"
    md_content += "| --- | --- |\n"

    for role_url, details in json_data["translations"].items():
        role_name_en = f"**{en_data['translations'][role_url]['name']}**"
        role_name_translated = f"**{details['name']}**"
        description_en = en_data["translations"][role_url]["description"]
        description_translated = details["description"]

        # Role name row
        md_content += f"| {role_name_translated} | {role_name_en} |\n"
        # Description row
        md_content += f"| {description_translated} | {description_en} |\n"

    # Translators section with ORCID hyperlink
    translator_lines = []
    for translator in json_data["metadata"]["translators"]:
        name = full_name(translator)
        if translator.get("ORCID"):
            name = f'[{name}](https://orcid.org/{translator["ORCID"]})'
        translator_lines.append(name)
    translator_names = ", ".join(translator_lines)
    md_content += f"\n## Translators\n\n{translator_names}\n\n"

    # Link to JSON
    md_content += f"## JSON Metadata\n\n[{JSON_URL}/{filename}]({JSON_URL}/{filename})\n\n"
    # License section
    md_content += "## License\n\n[CC-BY 4.0](https://creativecommons.org/licenses/by/4.0/)"
    # copyright is held by the translators together with the originators of CRediT
    md_content += f" {translator_names}, Brand, Allen, Altman, Hlava, & Scott\n\n"

    # Translation procedure section
    translation_procedure = json_data["metadata"]["translationProcedure"]
    md_content += f"## Translation Procedure\n\n{translation_procedure}"

    # Translation version section (a translation without a version is an error)
    md_content += f"\n## Translation Version\n\n **{json_data['version']}**.\n"

    return md_content


def render_page(json_data, en_data, filename, existing):
    """Markdown for one translation. Keeps the old date if nothing else changed."""
    if existing is not None:
        old_date = DATE_RE.search(existing)
        if old_date:
            same_content = json_to_md(json_data, en_data, filename, old_date.group(1))
            if same_content == existing:
                return existing
    return json_to_md(json_data, en_data, filename, today())


def describe(exc):
    if isinstance(exc, KeyError):
        return f"missing key {exc}"
    if isinstance(exc, json.JSONDecodeError):
        return f"not valid JSON ({exc.msg}, line {exc.lineno})"
    if isinstance(exc, UnicodeDecodeError):
        return "not valid UTF-8"
    return str(exc) or type(exc).__name__


def remove_stale_markdown(expected_stems):
    """Delete generated Markdown files whose JSON file no longer exists."""
    removed = []
    for md_path in sorted(MD_DIR.glob("*.md")):
        if md_path.stem in expected_stems:
            continue
        if GENERATED_MARKER in md_path.read_text(encoding="utf-8"):
            md_path.unlink()
            removed.append(md_path.name)
            print(f"Removed {md_path.name} (no matching JSON file)")
    return removed


def main():
    if not TRANSLATIONS_DIR.is_dir():
        print(f"Directory not found: {TRANSLATIONS_DIR}")
        return 1
    MD_DIR.mkdir(exist_ok=True)

    try:
        en_data = load_json(TRANSLATIONS_DIR / SOURCE_FILE)
    except (OSError, ValueError) as exc:
        print(f"Cannot read the English source text {SOURCE_FILE}: {describe(exc)}")
        return 1

    sources = sorted(p for p in TRANSLATIONS_DIR.glob("*.json") if p.name != SOURCE_FILE)
    problems = []
    updated = unchanged = 0
    for json_path in sources:
        md_path = MD_DIR / (json_path.stem + ".md")
        try:
            json_data = load_json(json_path)
            existing = md_path.read_bytes().decode("utf-8") if md_path.exists() else None
            page = render_page(json_data, en_data, json_path.name, existing)
        except (OSError, ValueError, KeyError, TypeError, AttributeError) as exc:
            problems.append((json_path.name, describe(exc)))
            continue
        if page == existing:
            unchanged += 1
            continue
        md_path.write_bytes(page.encode("utf-8"))
        updated += 1
        print(f"Updated {md_path.name}")

    removed = remove_stale_markdown({p.stem for p in sources})
    print(f"\nMarkdown: {updated} updated, {unchanged} unchanged, {len(removed)} removed.")

    for name, message in problems:
        if ON_GITHUB:
            print(f"::error file=translations/{name}::Could not render {name}: {message}")
        else:
            print(f"ERROR {name}: {message}")
    if problems:
        print(f"{len(problems)} translation file(s) could not be rendered.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
